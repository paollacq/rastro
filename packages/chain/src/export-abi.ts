// Copies RastroRFQ's ABI and bytecode from the Foundry build into src/abi, so the app and the
// setup script don't need Foundry. Runs as part of `pnpm contracts:build`.
import { readFileSync, writeFileSync } from 'node:fs';

const artifact = new URL('../../../contracts/out/RastroRFQ.sol/RastroRFQ.json', import.meta.url);
const target = new URL('./abi/rastroRfq.ts', import.meta.url);

let build: { abi: unknown[]; bytecode: { object: string } };
try {
  build = JSON.parse(readFileSync(artifact, 'utf8'));
} catch {
  console.error('contracts/out/RastroRFQ.sol/RastroRFQ.json is missing. Run `pnpm contracts:build`.');
  process.exit(1);
}

writeFileSync(
  target,
  [
    '// Generated by `pnpm abi:export` from contracts/out/RastroRFQ.sol/RastroRFQ.json. Do not edit.',
    '',
    `export const rastroRfqAbi = ${JSON.stringify(build.abi, null, 2)} as const;`,
    '',
    `export const rastroRfqBytecode = '${build.bytecode.object}' as const;`,
    '',
  ].join('\n'),
);

console.log(`src/abi/rastroRfq.ts: ${build.abi.length} ABI items, ${(build.bytecode.object.length - 2) / 2} bytes of initcode`);
